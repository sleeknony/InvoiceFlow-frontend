const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "../..");

const files = [

    // ==========================================================
    // Renderer
    // ==========================================================

    "src/renderer/Styles/renderer.css",
    "src/renderer/Styles/DocumentRenderer.css",
    "src/renderer/Styles/PageRenderer.css",
    "src/renderer/Styles/PageManager.css",
    "src/renderer/Styles/PrintableSection.css",
    "src/renderer/Styles/PageHeader.css",
    "src/renderer/Styles/PageFooter.css",
    "src/renderer/Styles/PageBreak.css",
    "src/renderer/Styles/PrintLayout.css",
    "src/renderer/Styles/Print.css",

    // ==========================================================
    // Modern Template
    // ==========================================================

    "src/renderer/templates/Modern/ModernDocument.css",
    "src/renderer/templates/Modern/ModernTemplate.css",

    "src/renderer/templates/Modern/components/Header/Header.css",
    "src/renderer/templates/Modern/components/Footer/Footer.css",
    "src/renderer/templates/Modern/components/Addresses/Addresses.css",
    "src/renderer/templates/Modern/components/ItemsTable/ItemsTable.css",
    "src/renderer/templates/Modern/components/PaymentDetails/PaymentDetails.css",
    "src/renderer/templates/Modern/components/Totals/Totals.css",

    // ==========================================================
    // PRINT OVERRIDES
    // ==========================================================

    "src/renderer/templates/Modern/ModernTemplate.print.css"
];

const output = path.join(
    root,
    "Pdf",
    "Styles",
    "PdfStyles.css"
);

let bundle = `/*
============================================================

    AUTO GENERATED FILE

    DO NOT EDIT.

    Generated by:

        npm run build:pdfcss

============================================================
*/

`;

for (const relative of files) {

    const absolute = path.join(root, relative);

    if (!fs.existsSync(absolute)) {

        console.error("");
        console.error("Missing CSS:");
        console.error(relative);
        console.error("");

        process.exit(1);
    }

    bundle += `

/* ==========================================================
   ${relative}
========================================================== */

`;

    bundle += fs.readFileSync(absolute, "utf8");
    bundle += "\n";
}

fs.mkdirSync(path.dirname(output), {
    recursive: true
});

fs.writeFileSync(
    output,
    bundle,
    "utf8"
);

console.log("");
console.log("====================================");
console.log(" PDF stylesheet generated");
console.log("====================================");
console.log(output);
console.log("");